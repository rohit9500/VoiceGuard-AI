import os
from datetime import datetime
from fpdf import FPDF


class ReportGenerator:

    def __init__(self):

        os.makedirs("reports/generated_reports", exist_ok=True)

    def generate(
        self,
        filename,
        deepfake,
        deepfake_confidence,
        transcript,
        scam,
        scam_confidence,
        risk,
        level
    ):

        pdf = FPDF()

        pdf.set_auto_page_break(auto=True, margin=15)

        pdf.add_page()

        # ----------------------------
        # Load Unicode Font
        # ----------------------------

        pdf.add_font(
            "DejaVu",
            "",
            "assets/fonts/DejaVuSans.ttf"
        )

        pdf.set_font("DejaVu", size=20)

        pdf.cell(
            0,
            12,
            "VoiceGuard AI Analysis Report",
            new_x="LMARGIN",
            new_y="NEXT",
            align="C"
        )

        pdf.ln(4)

        pdf.set_font("DejaVu", size=11)

        pdf.cell(
            0,
            8,
            f"Generated : {datetime.now().strftime('%d-%m-%Y %H:%M:%S')}",
            new_x="LMARGIN",
            new_y="NEXT"
        )

        pdf.cell(
            0,
            8,
            f"File : {filename}",
            new_x="LMARGIN",
            new_y="NEXT"
        )

        pdf.ln(5)

        # ----------------------------
        # Results
        # ----------------------------

        pdf.set_font("DejaVu", size=14)

        pdf.cell(
            0,
            10,
            "Detection Results",
            new_x="LMARGIN",
            new_y="NEXT"
        )

        pdf.set_font("DejaVu", size=11)

        pdf.multi_cell(
            0,
            8,
            f"""
Deepfake Prediction : {deepfake}

Deepfake Confidence : {deepfake_confidence:.2f} %

Scam Category : {scam}

Scam Confidence : {scam_confidence:.2f} %

Risk Score : {risk:.2f} %

Risk Level : {level}
"""
        )

        # ----------------------------
        # Transcript
        # ----------------------------

        pdf.ln(3)

        pdf.set_font("DejaVu", size=14)

        pdf.cell(
            0,
            10,
            "Transcript",
            new_x="LMARGIN",
            new_y="NEXT"
        )

        pdf.set_font("DejaVu", size=11)

        pdf.multi_cell(
            0,
            8,
            transcript
        )

        # ----------------------------
        # Recommendation
        # ----------------------------

        pdf.ln(3)

        pdf.set_font("DejaVu", size=14)

        pdf.cell(
            0,
            10,
            "Recommendation",
            new_x="LMARGIN",
            new_y="NEXT"
        )

        pdf.set_font("DejaVu", size=11)

        if level == "HIGH":

            recommendation = (
                "High Risk detected.\n"
                "- Do not share OTP.\n"
                "- Disconnect the call immediately.\n"
                "- Verify the caller through official channels.\n"
                "- Report suspicious activity."
            )

        elif level == "MEDIUM":

            recommendation = (
                "Medium Risk detected.\n"
                "- Verify the caller's identity.\n"
                "- Do not disclose sensitive information."
            )

        else:

            recommendation = (
                "Low Risk detected.\n"
                "- No significant scam indicators found."
            )

        pdf.multi_cell(
            0,
            8,
            recommendation
        )

        pdf.ln(10)

        pdf.set_font("DejaVu", size=10)

        pdf.cell(
            0,
            8,
            "Generated by VoiceGuard AI",
            new_x="LMARGIN",
            new_y="NEXT",
            align="C"
        )

        output_path = os.path.join(
            "reports",
            "generated_reports",
            f"{filename}.pdf"
        )

        pdf.output(output_path)

        return output_path